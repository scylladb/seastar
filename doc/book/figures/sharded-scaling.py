#!/usr/bin/python3
# Writes figures/sharded-scaling.tex, chapter 15's figure of Shoal version
# 8's GETs a second, measured on 1 to 3 (or 4) shards, and projected to
# more with the model of "Did it pay?":
#
#   T(N) = N * T1 / (1 + f * (N - 1) / N)
#
# where T1 is one shard's throughput, and f the extra work of a forwarded
# request, as a fraction of a request's work; (N - 1) / N of the requests
# are forwarded. f is fitted to the two-shard measurement.
#
# Usage: scaling-figure.py T1 T2 T3 [T4]   (millions of GETs a second)
import sys
from pathlib import Path

measured = [float(a) for a in sys.argv[1:]]
t1, t2 = measured[0], measured[1]
f = 2 * (2 * t1 / t2 - 1)
max_n = 16


def model(n):
    return n * t1 / (1 + f * (n - 1) / n)


for n, t in enumerate(measured, 1):
    print(f'{n} shards: measured {t:.2f}, model {model(n):.2f}',
          file=sys.stderr)
print(f'f = {f:.3f}; model at {max_n}: {model(max_n):.2f}; slope '
      f'{t1 / (1 + f):.2f} per shard ({1 / (1 + f):.0%} of one shard)',
      file=sys.stderr)

# Scales: 1 shard is 5 mm, 1 million GETs a second is 2.5 mm.
xs, ys = 5, 2.5
top = 22


def pt(n, t):
    return f'({n * xs:.2f}, {t * ys:.2f})'


out = []
w = out.append
w('% Figure for chapter 15, "Did it pay?": Shoal version 8\'s GETs a')
w('% second, measured on the laptop (circles), and projected to more')
w(f'% shards with T(N) = N*T1 / (1 + f*(N-1)/N), f = {f:.3f} fitted to')
w('% the two-shard measurement. Generated by figures/sharded-scaling.py')
w(f'% {" ".join(sys.argv[1:])}; edit that, not this.')
w('\\begin{tikzpicture}[x=1mm, y=1mm]')
w('  % Grid, axes and labels.')
for v in range(0, top + 1, 5):
    w(f'  \\draw[draw=fignote!40, line width=0.3pt] (0, {v * ys:.2f}) -- '
      f'({max_n * xs + 3}, {v * ys:.2f});')
    w(f'  \\node[note, anchor=east] at (-1, {v * ys:.2f}) {{{v}}};')
w(f'  \\draw[flow] (0, 0) -- (0, {top * ys + 3:.2f});')
w(f'  \\draw[draw=figink] (0, 0) -- ({max_n * xs + 3}, 0);')
w(f'  \\node[note, rotate=90, anchor=south] at (-7, {top * ys / 2:.2f}) '
  '{million GETs a second};')
for n in (1, 2, 3, 4, 8, 12, 16):
    w(f'  \\draw[draw=figink] ({n * xs}, 0) -- ({n * xs}, -1);')
    w(f'  \\node[note, anchor=north] at ({n * xs}, -1) {{{n}}};')
w(f'  \\node[note, anchor=north] at ({max_n * xs / 2}, -5.5) {{shards}};')
w('')
w('  % N times one shard: a dashed line.')
w(f'  \\draw[draw=fignote, line width=0.66pt, rare] {pt(1, t1)} -- '
  f'{pt(max_n, max_n * t1)};')
w(f'  \\node[note, anchor=south east, align=right] at {pt(max_n, max_n * t1)} '
  '{every shard as fast \\\\ as one shard alone};')
w('')
w('  % The model: a solid line, projected past the measurements.')
curve = ' -- '.join(pt(n / 4, model(n / 4))
                    for n in range(4, 4 * max_n + 1))
w(f'  \\draw[draw=figcool, line width=0.9pt] {curve};')
w(f'  \\node[font=\\sffamily\\footnotesize, text=figcool, anchor=north west, '
  f'align=left] at ({10 * xs + 1}, {model(10) * ys - 1.5:.2f}) '
  f'{{projected: each shard \\\\ adds {100 / (1 + f):.0f}\\% of one shard}};')
w('')
w('  % The measurements: circles.')
for n, t in enumerate(measured, 1):
    w(f'  \\draw[draw=figcool, fill=white, line width=0.9pt] {pt(n, t)} '
      'circle (1.2);')
w(f'  \\node[font=\\sffamily\\footnotesize, text=figcool, anchor=west, '
  f'align=left] at ({len(measured) * xs + 3}, {measured[-1] * ys - 1:.2f}) '
  '{measured};')
w('\\end{tikzpicture}')
Path(__file__).resolve().parent.parent.joinpath(
    'figures', 'sharded-scaling.tex').write_text('\n'.join(out) + '\n')
